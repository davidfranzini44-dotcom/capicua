export type Strings = (typeof dict)['es'];

/** Human message for an edge-function error code (`not_enough_chips:<name>` carries a name). */
export function errorText(t: Strings, code: string): string {
  const [key, who] = code.split(':');
  const msg = t.errors[key] ?? t.errors.server_error;
  return who ? `${who} ${msg}` : msg;
}
export const strings = (lang: Lang): Strings => dict[lang] as Strings;

export const LangContext = createContext<{ lang: Lang; t: Strings; setLang: (l: Lang) => void }>({
  lang: 'es',
  t: dict.es as Strings,
  setLang: () => {},
});
export const useI18n = () => useContext(LangContext);

export function loadLang(): Lang {
  try {
    const saved = localStorage.getItem('capicua.lang');
    if (saved === 'es' || saved === 'en') return saved;
  } catch { /* storage unavailable */ }
  return navigator.language?.startsWith('en') ? 'en' : 'es';
}

export function saveLang(lang: Lang) {
  try { localStorage.setItem('capicua.lang', lang); } catch { /* storage unavailable */ }
}
